function makePlan(
  baseRole: FurColorRole,
  overrides: Partial<FurRegionPlan>,
): FurRegionPlan {
  return FLEXIBLE_RENDER_REGIONS.reduce<FurRegionPlan>((plan, region) => {
    plan[region] = overrides[region] ?? baseRole;
    return plan;
  }, {} as FurRegionPlan);
}

