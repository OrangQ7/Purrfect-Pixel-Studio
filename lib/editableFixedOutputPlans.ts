export function createEditableAnalysisFromFixedOutput(
  templateId: FixedOutputTemplateId,
  imageHash = "matched",
): FlexibleCatAnalysis {
  return {
    ...DEFAULT_FLEXIBLE_ANALYSIS,
    analysisMode: "openai",
    imageHash,
    modeRecommendation: "fixed_template",
    coatPreset: templateCoatPreset[templateId],
    symmetry:
      templateId === "cow_cat_dark" || templateId === "cow_cat_grey"
        ? "mostly_symmetric"
        : "symmetric",
    mainColorRoles: DEFAULT_MAIN_COLOR_ROLES,
    furRegionPlan: EDITABLE_FIXED_OUTPUT_PLANS[templateId],
    featureRegionPlan: DEFAULT_FEATURE_REGION_PLAN,
    description: "Generated editable pixel cat color plan.",
    confidence: 1,
  };
}
